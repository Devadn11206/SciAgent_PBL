export function downloadBlob(name: string, blob: Blob) {
  const a = document.createElement('a')
  a.href = URL.createObjectURL(blob)
  a.download = name
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(a.href), 2000)
}
export const downloadText = (name: string, text: string, mime = 'text/plain') => downloadBlob(name, new Blob([text], { type: mime }))

export function latexTables(exp: Experiment): string {
  const bench = exp.bench
    .map((r) => `${r.method} & ${latexSci(r.relL2)} & ${latexSci(r.linf)} & ${latexSci(r.meanRes)} & ${r.driftPct}\\% & ${r.wallS} & ${r.memMB} \\\\`)
    .join('\n')
  const abl = exp.ablation
    .map((r, i) => {
      const d = i === 0 ? '---' : `${(((r.relL2 - exp.ablation[i - 1].relL2) / exp.ablation[i - 1].relL2) * 100).toFixed(1)}\\%`
      return `${r.trial} & ${r.action.replace(/[&%_#]/g, (c) => '\\' + c)} & ${latexSci(r.relL2)} & ${d} \\\\`
    })
    .join('\n')
  return `% ${exp.pdeName} — generated by SciAgent
\\begin{table}[t]
\\centering
\\caption{Benchmark comparison for the ${exp.pdeName}.}
\\begin{tabular}{lrrrrrr}
\\toprule
Method & Rel.\\ $L_2$ & $L_\\infty$ & Mean residual & Cons.\\ drift & Time (s) & Mem (MB) \\\\
\\midrule
${bench}
\\bottomrule
\\end{tabular}
\\end{table}

\\begin{table}[t]
\\centering
\\caption{Agentic self-correction ablation log.}
\\begin{tabular}{llrr}
\\toprule
Trial & Critic action & Rel.\\ $L_2$ & $\\Delta$ \\\\
\\midrule
${abl}
\\bottomrule
\\end{tabular}
\\end{table}
`
}

export async function downloadFigures(exp: Experiment) {
  const Plotly = (await import('plotly.js-dist-min')).default
  const f = buildFields(exp)
  const slices = buildSlices(exp, f)
  const figs: [string, any][] = [
    ['fig1a_reference', heatFigure('ref', exp, f, '2d', 'corrected', false, { height: 600 })],
    ['fig1b_agent_pinn', heatFigure('pred', exp, f, '2d', 'corrected', false, { height: 600 })],
    ['fig1c_abs_error', heatFigure('err', exp, f, '2d', 'corrected', false, { height: 600 })],
    ['fig1d_time_slices', overlayFigure(exp, f, slices, true, { height: 700 })],
  ]
  const zip = new JSZip()
  for (const [name, fig] of figs) {
    const layout = { ...fig.layout, paper_bgcolor: '#ffffff', width: 1000, height: fig.layout.height }
    const url: string = await Plotly.toImage({ data: fig.data, layout }, { format: 'png', width: 1000, height: layout.height, scale: 300 / 96 })
    zip.file(`${name}.png`, url.split(',')[1], { base64: true })
  }
  const blob = await zip.generateAsync({ type: 'blob' })
  downloadBlob(`sciagent_${exp.id}_figures_300dpi.zip`, blob)
}

const IC: Record<Experiment['fieldSpec']['kind'], string> = {
  burgers: 'np.array(-np.sin(np.pi * x))',
  allenCahn: 'x**2 * np.cos(np.pi * x)',
  nlse: '1.5 / np.cosh(1.5 * x)',
  duffing: '',
}

export function reproScript(exp: Experiment): string {
  const kind = exp.fieldSpec.kind
  const params = Object.fromEntries(exp.params.map((p) => [p.symbol, { value: p.value, inverse: p.mode === 'inverse', lo: p.lo, hi: p.hi, guess: p.guess }]))
  const cfg = JSON.stringify({ domain: exp.domain, params }, null, 2)

  const reference: Record<typeof kind, string> = {
    burgers: `def reference(cfg, N=2048):
    """Method-of-lines reference (implicit Radau, 2nd-order FD) for viscous Burgers."""
    from scipy.integrate import solve_ivp
    d, p = cfg["domain"], cfg["params"]
    x = np.linspace(d["xMin"], d["xMax"], N); dx = x[1] - x[0]
    nu = p["nu"]["value"]
    def rhs(t, u):
        du = np.zeros_like(u)
        du[1:-1] = -u[1:-1] * (u[2:] - u[:-2]) / (2 * dx) + nu * (u[2:] - 2 * u[1:-1] + u[:-2]) / dx**2
        return du
    t = np.linspace(d["tMin"], d["tMax"], 101)
    sol = solve_ivp(rhs, (t[0], t[-1]), ${IC.burgers}, t_eval=t, method="Radau", rtol=1e-8, atol=1e-10)
    return x, t, sol.y.T`,
    allenCahn: `def reference(cfg, N=1024):
    """Strang split-step FFT reference for Allen-Cahn (periodic)."""
    d, p = cfg["domain"], cfg["params"]
    L = d["xMax"] - d["xMin"]
    x = d["xMin"] + L * np.arange(N) / N
    k = 2 * np.pi * np.fft.fftfreq(N, d=L / N)
    eps = p["eps"]["value"]; dt = 1e-3
    nt = int(round((d["tMax"] - d["tMin"]) / dt))
    u = ${IC.allenCahn}
    lin = np.exp(-eps**2 * k**2 * dt / 2)
    out = [u.copy()]
    for _ in range(nt):
        u = np.fft.ifft(lin * np.fft.fft(u)).real
        u = u / np.sqrt(np.exp(-2 * dt) + u**2 * (1 - np.exp(-2 * dt)))  # exact flow of u' = u - u^3
        u = np.fft.ifft(lin * np.fft.fft(u)).real
        out.append(u.copy())
    return x, np.linspace(d["tMin"], d["tMax"], nt + 1), np.array(out)`,
    nlse: `def reference(cfg, N=1024):
    """Strang split-step Fourier reference for the cubic-quintic NLSE."""
    d, p = cfg["domain"], cfg["params"]
    L = d["xMax"] - d["xMin"]
    x = d["xMin"] + L * np.arange(N) / N
    k = 2 * np.pi * np.fft.fftfreq(N, d=L / N)
    beta, gamma, delta = p["beta"]["value"], p["gamma"]["value"], p["delta"]["value"]
    dt = 1e-3; nt = int(round((d["tMax"] - d["tMin"]) / dt))
    psi = (${IC.nlse}).astype(complex)
    half = np.exp(-1j * beta * k**2 * dt / 4)
    out = [np.abs(psi)]
    for _ in range(nt):
        psi = np.fft.ifft(half * np.fft.fft(psi))
        a = np.abs(psi)**2
        psi = psi * np.exp(1j * (gamma * a - delta * a**2) * dt)
        psi = np.fft.ifft(half * np.fft.fft(psi))
        out.append(np.abs(psi))
    return x, np.linspace(d["tMin"], d["tMax"], nt + 1), np.array(out)`,
    duffing: `def reference(cfg, nt=2001):
    """DOP853 reference for the forced Duffing oscillator."""
    from scipy.integrate import solve_ivp
    d, p = cfg["domain"], cfg["params"]
    delta, alpha, beta = p["delta"]["value"], p["alpha"]["value"], p["beta"]["value"]
    gamma, omega = p["gamma"]["value"], p["omega"]["value"]
    f = lambda t, s: [s[1], gamma * np.cos(omega * t) - delta * s[1] - alpha * s[0] - beta * s[0]**3]
    t = np.linspace(d["tMin"], d["tMax"], nt)
    sol = solve_ivp(f, (t[0], t[-1]), [0.5, 0.0], t_eval=t, method="DOP853", rtol=1e-12, atol=1e-12)
    return None, t, sol.y[0]`,
  }

  const residual: Record<typeof kind, string> = {
    burgers: `def residual(net, x, t, P):
    u = net(torch.cat([x, t], 1))
    u_t, u_x = grad(u, t), grad(u, x)
    return u_t + u * u_x - P["nu"] * grad(u_x, x)`,
    allenCahn: `def residual(net, x, t, P):
    u = net(torch.cat([x, t], 1))
    return grad(u, t) - P["eps"]**2 * grad(grad(u, x), x) + u**3 - u`,
    nlse: `def residual(net, x, t, P):
    h = net(torch.cat([x, t], 1)); u, v = h[:, :1], h[:, 1:2]
    a = u**2 + v**2
    nl = P["gamma"] * a - P["delta"] * a**2
    f_re = -grad(v, t) + 0.5 * P["beta"] * grad(grad(u, x), x) + nl * u
    f_im = grad(u, t) + 0.5 * P["beta"] * grad(grad(v, x), x) + nl * v
    return torch.cat([f_re, f_im], 1)`,
    duffing: `def residual(net, x, t, P):
    s = net(t)
    s_t = grad(s, t); s_tt = grad(s_t, t)
    return s_tt + P["delta"] * s_t + P["alpha"] * s + P["beta"] * s**3 - P["gamma"] * torch.cos(P["omega"] * t)`,
  }

  const outDim = kind === 'nlse' ? 2 : 1
  const inDim = kind === 'duffing' ? 1 : 2

  return `#!/usr/bin/env python3
"""
SciAgent reproducible script — ${exp.pdeName}
Mode: ${exp.mode} | Reference solver: ${exp.referenceSolver}

Agentic recipe (Critic actions): residual-adaptive refinement (RAR) -> causal weighting -> L-BFGS polish.
Requires: numpy, scipy, torch
"""
import numpy as np
import torch
import torch.nn as nn

torch.manual_seed(0); np.random.seed(0)
CFG = ${cfg.replace(/true/g, 'True').replace(/false/g, 'False')}


${reference[kind]}


def grad(y, x):
    return torch.autograd.grad(y, x, torch.ones_like(y), create_graph=True)[0]


${residual[kind]}


class Net(nn.Module):
    def __init__(self, width=64, depth=6):
        super().__init__()
        layers, d = [], ${inDim}
        for _ in range(depth):
            layers += [nn.Linear(d, width), nn.Tanh()]; d = width
        layers.append(nn.Linear(d, ${outDim}))
        self.f = nn.Sequential(*layers)
    def forward(self, z):
        return self.f(z)


def sample(n, d):
    x = torch.rand(n, 1) * (d["xMax"] - d["xMin"]) + d["xMin"]
    t = torch.rand(n, 1) * (d["tMax"] - d["tMin"]) + d["tMin"]
    return x.requires_grad_(), t.requires_grad_()


def train(cfg, adam_steps=4000, rar_rounds=2, lbfgs_steps=2000):
    d = cfg["domain"]
    # inverse coefficients are learned in log-space (positive-valued coefficients only)
    theta = {k: torch.tensor(float(np.log(max(v["guess"], 1e-6))), requires_grad=True)
             for k, v in cfg["params"].items() if v["inverse"]}
    fixed = {k: torch.tensor(float(v["value"])) for k, v in cfg["params"].items() if not v["inverse"]}
    coeffs = lambda: {**fixed, **{k: th.exp() for k, th in theta.items()}}
    net = Net()
    learnable = list(net.parameters()) + list(theta.values())
    opt = torch.optim.Adam(learnable, lr=1e-3)
    x, t = sample(10000, d)
    for rnd in range(rar_rounds + 1):
        for step in range(adam_steps):
            opt.zero_grad()
            loss = (residual(net, x, t, coeffs())**2).mean()
            loss.backward(); opt.step()
        if rnd < rar_rounds:
            # --- Critic action: residual-adaptive refinement (RAR) ---
            xn, tn = sample(20000, d)
            score = (residual(net, xn, tn, coeffs())**2).sum(1).detach()
            top = score.topk(2000).indices
            x = torch.cat([x.detach(), xn[top].detach()]).requires_grad_()
            t = torch.cat([t.detach(), tn[top].detach()]).requires_grad_()
    # --- Critic action: L-BFGS fine-tune ---
    lb = torch.optim.LBFGS(learnable, max_iter=lbfgs_steps, line_search_fn="strong_wolfe")
    def closure():
        lb.zero_grad()
        l = (residual(net, x, t, coeffs())**2).mean(); l.backward(); return l
    lb.step(closure)
    return net, {k: float(v) for k, v in coeffs().items()}


if __name__ == "__main__":
    xs, ts, uref = reference(CFG)
    net, P = train(CFG)
    print("recovered coefficients:", P)
`
}
